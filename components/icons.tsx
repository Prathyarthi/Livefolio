/** Maps a social platform id/label to the matching brand icon. */
export function PlatformIcon({
  platform,
  className = "h-4 w-4",
}: {
  platform: string;
  className?: string;
}) {
  const key = platform.toLowerCase();
  if (key.includes("github")) return <GithubIcon className={className} />;
  if (key.includes("linkedin")) return <LinkedinIcon className={className} />;
  if (key.includes("medium")) return <MediumIcon className={className} />;
  if (key.includes("leetcode")) return <LeetCodeMark className={className} />;
  if (key.includes("devto") || key.includes("dev.to")) return <DevtoIcon className={className} />;
  if (key.includes("hashnode")) return <HashnodeIcon className={className} />;
  if (key.includes("stackoverflow") || key.includes("stack overflow")) {
    return <StackOverflowIcon className={className} />;
  }
  if (key.includes("codeforces")) return <CodeforcesIcon className={className} />;
  if (key.includes("instagram")) return <InstagramIcon className={className} />;
  if (key.includes("twitter") || key === "x") return <TwitterIcon className={className} />;
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden
    >
      <circle cx="12" cy="12" r="10" />
      <path d="M2 12h20" />
      <path d="M12 2a15.3 15.3 0 0 1 4 10 15.3 15.3 0 0 1-4 10 15.3 15.3 0 0 1-4-10 15.3 15.3 0 0 1 4-10z" />
    </svg>
  );
}

